#!/usr/bin/env python3
"""Export the standalone Kaggle notebook to a script for code review only.

Do not run the exported script in GitHub Actions: model downloads and Kaggle
Secrets require an actual Kaggle GPU environment.
"""
from __future__ import annotations
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
path=ROOT/'notebooks'/'Rizzler_V9_Kaggle_Gemini_Specialist_Skill_Studio.ipynb'
notebook=json.loads(path.read_text(encoding='utf-8'))
sections=['# AUTOGENERATED / REVIEW ONLY. RUN THE NOTEBOOK ON KAGGLE INSTEAD.']
for idx,cell in enumerate(notebook['cells']):
    if cell.get('cell_type')=='code':
        sections.extend((f'\n# %% [notebook cell {idx}]\n',''.join(cell['source'])))
dest=ROOT/'build'/'rizzler_review_export.py'
dest.parent.mkdir(exist_ok=True)
dest.write_text('\n'.join(sections)+'\n',encoding='utf-8')
print(dest)
